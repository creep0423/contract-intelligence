#
#   run_offline_ocr.py         — 离线 OCR 清洗入口
#     - 处理扫描件/图片 PDF → 输出待人工复核的 Markdown
#     - 不写 Milvus、不激活知识库版本、不被在线问答调用
#     - 支持单文件（--input）和批量目录（--input-dir）
#
#   promote_ocr_candidates.py  — 提升已人工复核的 OCR 资料
#     - 只复制已标记"人工复核通过"的 Markdown 到场景资料目录
#     - 默认 dry-run 预览，--apply 才真正复制
#     - 复制后的资料仍需通过知识库版本重建和质量门禁才能上线
#
# 安全约束：
#   - OCR 输出不能直接写入 active 知识库（可能识别错金额、日期、合同号）
#   - 必须经过人工复核 → 提升到场景目录 → 质量门禁 → 评测门禁 四步流程
